# Every sector appearing above, sorted - drives the Screener's sector filter.
SECTORS: tuple[str, ...] = tuple(sorted(set(SECTOR_BY_SYMBOL.values())))

# Deliberately not a random pick: an unknown symbol (a synthetic test ticker,
# or something newly typed into the curated watchlist) has no known sector, and
# saying so is more honest than inventing one.
UNKNOWN_SECTOR = "Unknown"


def sector_for(symbol: str) -> str:
    """Returns the symbol's sector, or UNKNOWN_SECTOR if it is not mapped."""
    return SECTOR_BY_SYMBOL.get(symbol.upper(), UNKNOWN_SECTOR)
